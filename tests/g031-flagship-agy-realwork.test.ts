/**
 * GOAL-031 / GP-41 RM-004 M1 实战运营与 agy 旗舰真实闭环测试
 */

import { test, describe, beforeEach, afterEach } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, mkdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { tmpdir } from 'node:os';
import { DispatchPipeline } from '../src/web/dispatch.ts';
import { readCarveoutToken } from '../src/web/carveouts.ts';
import { buildAgyContract } from '../src/adapters/agy.ts';
import { runVerifier } from '../src/orchestration/verifier.ts';
import { executePipelineSOP } from '../src/orchestration/topology.ts';

describe('GOAL-031: RM-004 M1 Real-Work Operations with AGY Executor', () => {
  let tmpDir: string;
  let approvalRoot: string;
  let runtimeRoot: string;
  let tokenPath: string;
  let pipeline: DispatchPipeline;

  beforeEach(() => {
    tmpDir = mkdtempSync(path.join(tmpdir(), 'mush-test-g031-'));
    approvalRoot = path.join(tmpDir, 'runtime', 'approvals');
    runtimeRoot = path.join(tmpDir, 'runtime');
    tokenPath = path.join(tmpDir, '.mush', 'carveout-token');
    mkdirSync(approvalRoot, { recursive: true });
    mkdirSync(runtimeRoot, { recursive: true });

    pipeline = new DispatchPipeline({
      workspaceRoot: tmpDir,
      approvalRoot,
      ledgerPath: path.join(runtimeRoot, 'budget-ledger.jsonl'),
      carveoutsPath: path.join(runtimeRoot, 'carveouts.jsonl'),
      carveoutTokenPath: tokenPath,
      runAdapter: async (_contract, _prompt, _opts) => ({
        exitCode: 0,
        stdout: 'AGY execution succeeded with zero defects',
        stderr: '',
        timedOut: false,
        childKilled: false,
      }),
    });
  });

  afterEach(() => {
    rmSync(tmpDir, { recursive: true, force: true });
  });

  test('1. AGY Adapter Contract & Roster Compliance', () => {
    const defaultContract = buildAgyContract();
    assert.strictEqual(defaultContract.adapter_id, 'agy');
    assert.strictEqual(defaultContract.executable, 'agy');
    assert.strictEqual(defaultContract.expected_model_id, 'gemini-3.7-flash-high');
    assert.strictEqual(defaultContract.role, 'executor');
    assert.deepStrictEqual(defaultContract.effort_levels, ['LOW', 'MEDIUM', 'HIGH']);
    assert.ok((defaultContract.variants ?? []).includes('gemini-3.7-flash-high'));
    assert.ok((defaultContract.variants ?? []).includes('gemini-3.1-pro-high'));

    const customContract = buildAgyContract('gemini-3.1-pro-high');
    assert.strictEqual(customContract.expected_model_id, 'gemini-3.1-pro-high');
  });

  test('2. AGY Execution under Carve-out Declarative Whitelist Gate', async () => {
    const targetSliceDir = path.join(tmpDir, 'src', 'features', 'module-a');
    mkdirSync(targetSliceDir, { recursive: true });

    // 1. 未声明 carve-out 前尝试在特定目录执行写操作 ➔ 拦截
    await assert.rejects(
      async () => {
        await pipeline.dispatch({
          adapter_id: 'agy',
          prompt: 'Refactor module-a logic',
          cwd: targetSliceDir,
          real: false,
        });
      },
      (err: Error) => err.message.includes('cwd requires carveout_id'),
    );

    // 2. 获取 carve-out 令牌并授权单切片
    const token = readCarveoutToken(tokenPath);
    assert.ok(token !== null);
    const carveout = pipeline.grantCarveout(
      {
        task_ref: 'TASK-M1-AGY-001',
        paths: [targetSliceDir],
        expires_at: '2099-01-01T00:00:00.000Z',
      },
      token,
    );
    assert.strictEqual(carveout.status, 'ACTIVE');

    // 3. 携带合法 carveout_id 派发 ➔ 成功受理 (dry-run)
    const record = await pipeline.dispatch({
      adapter_id: 'agy',
      model_id: 'gemini-3.7-flash-high',
      prompt: 'Implement feature in module-a',
      cwd: targetSliceDir,
      carveout_id: carveout.carveout_id,
      real: false,
    });
    assert.strictEqual(record.status, 'DRY_RUN');
    assert.strictEqual(record.carveout_id, carveout.carveout_id);
  });

  test('3. AGY Multi-Topology Execution with Independent Verifier Gate', async () => {
    // 1. Pipeline SOP 工序流水线测试（agy 作为 Code 生成犬）
    const sopResult = await executePipelineSOP({
      initialPrompt: 'Create resilient parser module',
      pipelineSteps: [
        {
          step_name: 'SPEC_DESIGN',
          dog_id: 'agy',
        },
        {
          step_name: 'CODE_IMPLEMENT',
          dog_id: 'agy',
        },
      ],
      runStep: async (dogId, prompt) => ({
        output: `Generated by ${dogId} for ${prompt.slice(0, 30)}`,
        exitCode: 0,
      }),
    });

    assert.strictEqual(sopResult.success, true);
    assert.strictEqual(sopResult.steps.length, 2);

    // 2. Verifier 解耦检查：由独立 verifier (zcode) 审查 agy 产出工件
    const report = await runVerifier({
      generatorId: 'agy',
      verifierId: 'zcode',
      facet: 'SECURITY',
      prompt: 'Verify code security',
      artifactContent: 'export function parse() { return true; }',
    });
    assert.strictEqual(report.decision, 'PASS');
    assert.strictEqual(report.issues.length, 0);
  });

  test('4. End-to-End Real Operations Flow with Approval Gate & Receipts', async () => {
    // 1. 派发真实任务 (real: true) 触发审批拦截卡
    const blockedRecord = await pipeline.dispatch({
      adapter_id: 'agy',
      model_id: 'gemini-3.7-flash-high',
      prompt: 'Production code update for RM-004 M1',
      real: true,
    });
    assert.strictEqual(blockedRecord.status, 'BLOCKED_WAITING_OWNER');

    // 2. 人类审批放行：签发单次审批令牌
    pipeline.grantApprovalToken(blockedRecord.dispatch_id);

    // 3. 凭 approved_via 重跑派发消费令牌
    const approved = await pipeline.rerun(blockedRecord.dispatch_id, {
      real: true,
      approved_via: blockedRecord.dispatch_id,
    });
    assert.strictEqual(approved.status, 'PASS');
    assert.notStrictEqual(approved.dispatch_id, blockedRecord.dispatch_id);
    assert.strictEqual(pipeline.get(blockedRecord.dispatch_id)?.status, 'SUPERSEDED');

    // 4. 验证 receipts 生成并落盘
    assert.ok(approved.receipt_path !== null);
    assert.ok(existsSync(approved.receipt_path!));
  });
});